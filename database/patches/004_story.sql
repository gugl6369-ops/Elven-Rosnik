-- Patch: ephemeral stories feed (schema app)
-- Apply manually against elfi_ros. Idempotent.
-- See docs/backend-product-spec-and-guide.md §10.

SET search_path TO app, public;

CREATE TABLE IF NOT EXISTS story (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    media_url    VARCHAR(2048) NOT NULL,
    media_type   VARCHAR(16) NOT NULL CHECK (media_type IN ('image', 'video')),
    caption      TEXT,
    link_url     VARCHAR(2048),
    active_from  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    active_until TIMESTAMPTZ NOT NULL,
    is_active    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_story_active ON story(is_active, active_until DESC)
    WHERE is_active = true;

COMMENT ON TABLE story IS 'Short-lived admin stories for the home feed strip.';