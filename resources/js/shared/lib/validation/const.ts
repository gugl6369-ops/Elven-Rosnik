import { z } from 'zod';

export const emailValid = z
    .string()
    .regex(
        /^[\w_.+\-]+@[\w\-]+\.[\w\-]{2,}$/,
        'Введите корректный email',
    )
    .regex(/^[\w.\-@_+$]+$/, 'Недопустимые символы')
    .max(255, 'Максимум 255 символов');

export const usernameValid = z
    .string()
    .trim()
    .min(1, 'Укажите уникальное имя')
    .max(64, 'Максимум 64 символа')
    .regex(
        /^[a-zA-Z0-9_]+$/,
        'Допустимы латиница, цифры и _',
    );

export const passwordValid = z
    .string()
    .min(6, 'Минимум 6 символов')
    .max(30, 'Максимум 30 символов')
    .regex(
        /^[A-Za-z0-9!#%*+\-\/=?_~\.,@\$]+$/,
        'Недопустимые символы',
    )
    .regex(/^.*[A-Z].*$/, 'Пароль должен содержать минимум одну заглавную букву')
    .regex(
        /^.*[!#%*+\-\/=?_~\.,@\$].*$/,
        'Пароль должен содержать минимум один спецсимвол',
    );